import { Document, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, WidthType, Packer, BorderStyle } from 'docx';
import ExcelJS from 'exceljs';

/**
 * Generate a DOCX proposal document
 */
export const generateProposalDOCX = async (rfpData) => {
  const { title, analysis, proposal, compliance_matrix, review } = rfpData;

  const children = [];

  // Title
  children.push(
    new Paragraph({
      text: title || 'RFP Proposal',
      heading: HeadingLevel.TITLE,
      spacing: { after: 400 },
    })
  );

  children.push(
    new Paragraph({
      text: `Generated by ProposalIQ | ${new Date().toLocaleDateString()}`,
      spacing: { after: 400 },
      children: [
        new TextRun({
          text: `Generated by ProposalIQ | ${new Date().toLocaleDateString()}`,
          italics: true,
          color: '888888',
          size: 20,
        }),
      ],
    })
  );

  // Executive Summary from Analysis
  if (analysis?.summary) {
    children.push(
      new Paragraph({ text: 'Executive Summary', heading: HeadingLevel.HEADING_1, spacing: { before: 400 } })
    );
    children.push(
      new Paragraph({ text: analysis.summary, spacing: { after: 200 } })
    );
  }

  // Key Requirements
  if (analysis?.requirements?.length > 0) {
    children.push(
      new Paragraph({ text: 'Key Requirements', heading: HeadingLevel.HEADING_1, spacing: { before: 400 } })
    );
    for (const req of analysis.requirements) {
      children.push(
        new Paragraph({
          text: `• ${req}`,
          spacing: { after: 100 },
        })
      );
    }
  }

  // Proposal Content
  if (proposal?.content) {
    children.push(
      new Paragraph({ text: 'Proposal', heading: HeadingLevel.HEADING_1, spacing: { before: 400 } })
    );

    const sections = proposal.content.split('\n\n');
    for (const section of sections) {
      children.push(
        new Paragraph({ text: section, spacing: { after: 200 } })
      );
    }
  }

  // Risk Assessment
  if (analysis?.risks?.length > 0) {
    children.push(
      new Paragraph({ text: 'Risk Assessment', heading: HeadingLevel.HEADING_1, spacing: { before: 400 } })
    );
    for (const risk of analysis.risks) {
      children.push(
        new Paragraph({
          text: `⚠ ${risk}`,
          spacing: { after: 100 },
        })
      );
    }
  }

  // Disclaimer
  children.push(
    new Paragraph({ text: '', spacing: { before: 600 } })
  );
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: 'Disclaimer: This proposal was generated with AI assistance via ProposalIQ. All content should be reviewed by qualified professionals before submission. ProposalIQ does not guarantee the accuracy or completeness of AI-generated content.',
          italics: true,
          color: '999999',
          size: 18,
        }),
      ],
    })
  );

  const doc = new Document({
    sections: [{ children }],
  });

  return await Packer.toBuffer(doc);
};

/**
 * Generate compliance matrix as Excel spreadsheet
 */
export const generateComplianceExcel = async (rfpData) => {
  const { title, compliance_matrix } = rfpData;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'ProposalIQ';
  workbook.created = new Date();

  // Compliance Matrix Sheet
  const sheet = workbook.addWorksheet('Compliance Matrix');

  // Header styling
  const headerStyle = {
    font: { bold: true, color: { argb: 'FFFFFFFF' }, size: 12 },
    fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4C1D95' } },
    alignment: { horizontal: 'center', vertical: 'middle', wrapText: true },
    border: {
      top: { style: 'thin' },
      bottom: { style: 'thin' },
      left: { style: 'thin' },
      right: { style: 'thin' },
    },
  };

  // Setup columns
  sheet.columns = [
    { header: '#', key: 'index', width: 6 },
    { header: 'Requirement', key: 'requirement', width: 45 },
    { header: 'Response', key: 'response', width: 45 },
    { header: 'Status', key: 'status', width: 15 },
    { header: 'Notes', key: 'notes', width: 30 },
  ];

  // Style header row
  const headerRow = sheet.getRow(1);
  headerRow.eachCell((cell) => {
    cell.style = headerStyle;
  });
  headerRow.height = 30;

  // Add data rows
  if (compliance_matrix?.items?.length > 0) {
    compliance_matrix.items.forEach((item, index) => {
      const row = sheet.addRow({
        index: index + 1,
        requirement: item.requirement || '',
        response: item.response || '',
        status: item.status || 'Pending',
        notes: item.notes || '',
      });

      row.eachCell((cell) => {
        cell.alignment = { wrapText: true, vertical: 'top' };
        cell.border = {
          top: { style: 'thin' },
          bottom: { style: 'thin' },
          left: { style: 'thin' },
          right: { style: 'thin' },
        };
      });

      // Color code status
      const statusCell = row.getCell('status');
      if (item.status === 'Compliant') {
        statusCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF22C55E' } };
      } else if (item.status === 'Partial') {
        statusCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFBBF24' } };
      } else if (item.status === 'Non-Compliant') {
        statusCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEF4444' } };
      }
    });
  }

  // Summary Sheet
  const summarySheet = workbook.addWorksheet('Summary');
  summarySheet.columns = [
    { header: 'Metric', key: 'metric', width: 30 },
    { header: 'Value', key: 'value', width: 30 },
  ];

  const summaryHeaderRow = summarySheet.getRow(1);
  summaryHeaderRow.eachCell((cell) => {
    cell.style = headerStyle;
  });

  summarySheet.addRow({ metric: 'RFP Title', value: title || 'N/A' });
  summarySheet.addRow({ metric: 'Generated Date', value: new Date().toLocaleDateString() });
  summarySheet.addRow({ metric: 'Total Requirements', value: compliance_matrix?.items?.length || 0 });
  summarySheet.addRow({
    metric: 'Compliant',
    value: compliance_matrix?.items?.filter((i) => i.status === 'Compliant').length || 0,
  });
  summarySheet.addRow({
    metric: 'Partial',
    value: compliance_matrix?.items?.filter((i) => i.status === 'Partial').length || 0,
  });
  summarySheet.addRow({
    metric: 'Non-Compliant',
    value: compliance_matrix?.items?.filter((i) => i.status === 'Non-Compliant').length || 0,
  });

  return await workbook.xlsx.writeBuffer();
};

export default { generateProposalDOCX, generateComplianceExcel };
